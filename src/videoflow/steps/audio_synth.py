def _style_audio(context: PipelineContext) -> dict[str, Any]:
    path = context.output / "style" / "style-guide.json"
    try:
        payload = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    audio = payload.get("audio") if isinstance(payload, dict) else None
    return audio if isinstance(audio, dict) else {}


class ComposeParams(BaseModel):
    model_config = ConfigDict(extra="forbid")

    bpm: float = Field(default=90.0, ge=40.0, le=220.0)
    root_midi: int = Field(default=45, ge=12, le=96)
    seed: int = Field(default=7, ge=0, le=2**31 - 1)
    duration_sec: float = Field(default=0.0, ge=0.0, le=4 * 3600)
    stems: bool = True


@register_step
class AudioComposeStep(BaseStep):
    type = "audio.compose"
    title = "Compose music"
    description = (
        "Generate a deterministic, copyright-free music bed and stems with numpy synthesis."
    )
    status = "available"
    icon = "♫"
    color = "#a78bfa"
    produces = ("audio_music",)
    params_model = ComposeParams

    def run(self, context: PipelineContext, params: BaseModel, io: StepIO) -> None:
        options = ComposeParams.model_validate(params)
        sample_rate = context.media.audio_sample_rate if context.media is not None else 48000
        audio = _style_audio(context)
        try:
            bpm = float(audio.get("bpm") or audio.get("tempo_bpm") or options.bpm)
        except (TypeError, ValueError):
            bpm = options.bpm
        try:
            root_midi = int(audio.get("root_midi") or options.root_midi)
        except (TypeError, ValueError):
            root_midi = options.root_midi
        duration = options.duration_sec or float(
            context.metadata.get("narration_duration_sec") or 0.0
        )
        if duration <= 0.0:
            duration = context.duration_samples() / max(1, sample_rate)
        if duration <= 0.0:
            raise ExportError(
                "Music composition needs a duration, narration timing, or ingested media."
            )
        payload = compose_music(
            context.output / "audio" / "music",
            duration_sec=duration,
            bpm=bpm,
            root_midi=root_midi,
            seed=options.seed,
            sample_rate=sample_rate,
        )
        plan = {
            **payload,
            "generated_by": "procedural",
            "style_audio": audio,
            "license": "generated by VideoFlow; no third-party recording",
        }
        target = context.output / "audio" / "music-plan.json"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(plan, indent=2) + "\n", encoding="utf-8")
        files = payload.get("files")
        if isinstance(files, dict):
            music_path = str(files.get("mix") or "")
            context.artifacts["audio_music"] = music_path
            # Backward-compatible alias for recipes and clients built on the
            # old output-port label.
            context.artifacts["music_bed"] = music_path
        context.artifacts["audio_music_plan"] = str(target)
        context.metadata["audio_music"] = plan
        context.hashes["audio.compose"] = digest_payload(plan)
        io.report(100, f"Music bed generated ({duration:.1f}s)")

    def cache_outputs(self, context: PipelineContext) -> tuple[Path, ...]:
        return tuple(
            Path(context.artifacts[key])
            for key in ("audio_music", "audio_music_plan")
            if context.artifacts.get(key)
        )


class SfxSynthParams(BaseModel):
    model_config = ConfigDict(extra="forbid")

    max_cues: int = Field(default=60, ge=0, le=300)
    kinds: list[str] = Field(
        default_factory=lambda: [
            "paper_turn",
            "keyboard_click",
            "marker_underline",
            "whoosh",
            "riser",
            "impact",
        ]
    )
    use_scenes: bool = True


@register_step
class SfxSynthStep(BaseStep):
    type = "sfx.synthesize"
    title = "Synthesize Foley"
    description = (
        "Generate copyright-free Foley cues and place them at scene starts or at a default cadence."
    )
    status = "available"
    icon = "♪"
    color = "#a78bfa"
    params_model = SfxSynthParams

    def run(self, context: PipelineContext, params: BaseModel, io: StepIO) -> None:
        options = SfxSynthParams.model_validate(params)
        style_kinds = _style_audio(context).get("foley")
        kinds = (
            [str(item) for item in style_kinds if str(item).strip()]
            if isinstance(style_kinds, list) and style_kinds
            else list(options.kinds)
        ) or list(options.kinds)
        cues: list[dict[str, Any]] = []
        scenes_path = context.output / "motion" / "render-manifest.json"
        if options.use_scenes:
            try:
                payload = json.loads(scenes_path.read_text(encoding="utf-8"))
                scenes = payload.get("scenes", []) if isinstance(payload, dict) else []
            except (OSError, ValueError):
                scenes = []
            for index, scene in enumerate(scenes):
                if not isinstance(scene, dict):
                    continue
                kind = kinds[index % max(1, len(kinds))]
                cues.append(
                    {
                        "kind": kind,
                        "start_sec": float(scene.get("start_sec") or 0.0),
                        "gain": 0.35 if kind != "impact" else 0.5,
                    }
                )
        if not cues:
            duration = float(context.metadata.get("narration_duration_sec") or 0.0)
            if duration <= 0.0:
                duration = context.duration_samples() / (
                    context.media.audio_sample_rate if context.media is not None else 48000
                )
            current = 0.0
            while current < duration and len(cues) < options.max_cues:
                cues.append(
                    {
                        "kind": kinds[len(cues) % max(1, len(kinds))],
                        "start_sec": round(current, 3),
                        "gain": 0.3,
                    }
                )
                current += 30.0
        cues = cues[: options.max_cues]
        payload = synthesize_foley(context.output / "audio" / "sfx", cues)
        target = context.output / "audio" / "sfx-plan.json"
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(json.dumps(payload, indent=2) + "\n", encoding="utf-8")
        context.metadata["sfx_cues"] = payload["cues"]
        context.artifacts["sfx_cues"] = str(target)
        context.hashes["sfx.synthesize"] = digest_payload(payload)
        io.report(100, f"{len(cues)} Foley cue(s) generated")

    def cache_outputs(self, context: PipelineContext) -> tuple[Path, ...]:
        path = context.artifacts.get("sfx_cues")
        return (Path(path),) if path else ()


class MixParams(BaseModel):
    model_config = ConfigDict(extra="forbid")

    music_gain: float = Field(default=0.22, ge=0.0, le=1.0)
    sfx_gain: float = Field(default=0.55, ge=0.0, le=1.0)
    sfx_notch_hz: float = Field(default=0.0, ge=0.0, le=20000.0)
    sfx_notch_db: float = Field(default=0.0, ge=-24.0, le=24.0)
    duck_music: bool = True
    duck_threshold: float = Field(default=0.02, gt=0.0, le=1.0)
    duck_ratio: float = Field(default=8.0, ge=1.0, le=20.0)
    duck_attack_ms: int = Field(default=20, ge=1, le=500)
    duck_release_ms: int = Field(default=300, ge=10, le=2000)
    target_lufs: float = Field(default=0.0, ge=-30.0, le=0.0)
    output_name: str = Field(default="final.wav", max_length=120)
    master_path: str = ""
    music_path: str = ""
    music_arc: Literal["none", "three_act"] = "none"
    arc_hook_ratio: float = Field(default=0.2, ge=0.05, le=0.5)
    arc_outro_ratio: float = Field(default=0.8, ge=0.5, le=0.95)


@register_step
class AudioMixStep(BaseStep):
    type = "audio.mix"
    title = "Mix dialogue, music, and Foley"
    description = (
        "Mix the dialogue master with the generated music bed and Foley cues, "
        "then expose the result as the audio master for QA and export."
    )
    status = "available"
    icon = "♬"
    color = "#a78bfa"
    produces = ("audio_mix",)
    params_model = MixParams

    def run(self, context: PipelineContext, params: BaseModel, io: StepIO) -> None:
        options = MixParams.model_validate(params)
        dialogue = Path(
            options.master_path
            or context.artifacts.get("audio_master")
            or context.output / "audio" / "master.wav"
        ).expanduser()
        if not dialogue.is_file():
            raise ExportError("Audio mix requires the dialogue master.")
        music_value = (
            options.music_path
            or context.artifacts.get("audio_music")
            or context.artifacts.get("music_bed")
        )
        music = Path(music_value).expanduser() if music_value else None
        if music is not None and not music.is_file():
            plan_value = context.artifacts.get("audio_music_plan")
            if plan_value:
                try:
                    plan = json.loads(Path(plan_value).read_text(encoding="utf-8"))
                    candidate = (plan.get("files") or {}).get("mix")
                    if candidate:
                        music = Path(str(candidate)).expanduser()
                except (OSError, ValueError, TypeError):
                    pass
        cues: list[dict[str, Any]] = []
        sfx_plan = context.artifacts.get("sfx_cues")
        if sfx_plan:
            try:
                payload = json.loads(Path(sfx_plan).read_text(encoding="utf-8"))
                cues = payload.get("cues", []) if isinstance(payload, dict) else []
            except (OSError, ValueError):
                cues = []
        target = context.output / "audio" / options.output_name
        target.parent.mkdir(parents=True, exist_ok=True)
        if music is None or not music.is_file():
            if cues:
                context.warnings.append("Audio mix: no music bed; mixing Foley only.")
            else:
                shutil.copy2(dialogue, target)
                self._publish(context, target)
                context.warnings.append("Audio mix: no music or Foley; copied dialogue.")
                io.report(100, "No music/Foley; dialogue master copied")
                return
        binary = find_binary("ffmpeg")
        if binary is None:
            raise ExportError("FFmpeg is required for the audio mix.")
        inputs: list[str] = ["-i", str(dialogue)]
        if music is not None and music.is_file():
            music_meta = context.metadata.get("audio_music", {})
            if not isinstance(music_meta, dict) or not music_meta:
                plan_value = context.artifacts.get("audio_music_plan")
                if plan_value:
                    try:
                        music_meta = json.loads(Path(plan_value).read_text(encoding="utf-8"))
                    except (OSError, ValueError):
                        music_meta = {}
            looped = (
                isinstance(music_meta, dict) and float(music_meta.get("loop_seconds") or 0.0) > 0.0
            )
            if looped:
                inputs.extend(["-stream_loop", "-1", "-i", str(music)])
            else:
                inputs.extend(["-i", str(music)])
        cue_paths: list[tuple[dict[str, Any], Path]] = []
        for cue in cues[:40]:
            path = Path(str(cue.get("path") or ""))
            if path.is_file():
                cue_paths.append((cue, path))
                inputs.extend(["-i", str(path)])
        style_audio = _style_audio(context)
        try:
            notch_hz = float(style_audio.get("keyboard_notch_hz") or 0.0)
        except (TypeError, ValueError):
            notch_hz = 0.0
        try:
            notch_db = float(style_audio.get("keyboard_notch_db") or 0.0)
        except (TypeError, ValueError):
            notch_db = 0.0
        notch_hz = options.sfx_notch_hz or notch_hz
        notch_db = options.sfx_notch_db if options.sfx_notch_db != 0 else notch_db
        filter_parts = []
        mix_labels = ["[0:a]"]
        if music is not None and music.is_file():
            volume = f"{options.music_gain}"
            if options.music_arc == "three_act":
                rate = context.media.audio_sample_rate if context.media else 48000
                samples = timeline_duration_samples(context.state) if context.state else 0
                duration = (samples or context.duration_samples()) / max(1, rate)
                hook = duration * options.arc_hook_ratio
                outro = duration * options.arc_outro_ratio
                quiet = options.music_gain * 0.55
                loud = min(1.0, options.music_gain * 1.25)
                volume = (
                    f"'if(lt(t,{hook:.3f}),{quiet:.4f},"
                    f"if(lt(t,{outro:.3f}),{loud:.4f},{options.music_gain:.4f}))'"
                )
            chain = f"volume={volume}:eval=frame,atrim=0,asetpts=PTS-STARTPTS"
            if options.duck_music:
                filter_parts.append("[0:a]asplit=2[voice][sidechain]")
                filter_parts.append(f"[1:a]{chain}[musicraw]")
                filter_parts.append(
                    f"[musicraw][sidechain]sidechaincompress="
                    f"threshold={options.duck_threshold}:"
                    f"ratio={options.duck_ratio}:"
                    f"attack={options.duck_attack_ms}:"
                    f"release={options.duck_release_ms}[music]"
                )
                mix_labels[0] = "[voice]"
            else:
                filter_parts.append(f"[1:a]{chain}[music]")
            mix_labels.append("[music]")
        base_index = 2 if music is not None and music.is_file() else 1
        for offset, (cue, _path) in enumerate(cue_paths):
            index = base_index + offset
            start_ms = max(0, int(float(cue.get("start_sec") or 0.0) * 1000))
            gain = options.sfx_gain * float(cue.get("gain") or 0.35)
            chain = f"volume={gain}"
            if notch_hz > 0 and notch_db != 0:
                chain += f",equalizer=f={notch_hz}:width_type=h:width=1000:g={notch_db}"
            filter_parts.append(f"[{index}:a]{chain},adelay={start_ms}:all=1[sfx{index}]")
            mix_labels.append(f"[sfx{index}]")
        loudness = (
            f",loudnorm=I={options.target_lufs}:TP=-1.5:LRA=11" if options.target_lufs < 0 else ""
        )
        filter_parts.append(
            f"{''.join(mix_labels)}amix=inputs={len(mix_labels)}:"
            "duration=first:dropout_transition=2:normalize=0,"
            f"alimiter=limit=0.95{loudness}[mix]"
        )
        command = [
            binary,
            "-hide_banner",
            "-loglevel",
            "error",
            "-y",
            *inputs,
            "-filter_complex",
            ";".join(filter_parts),
            "-map",
            "[mix]",
            "-c:a",
            "pcm_s16le",
            str(target),
        ]
        completed = subprocess.run(command, capture_output=True, text=True, check=False)
        if completed.returncode != 0:
            raise ExportError(
                "Audio mix failed: " + (completed.stderr.strip()[-400:] or "unknown error")
            )
        self._publish(context, target)
        io.report(100, f"Mixed {len(cue_paths)} Foley cue(s) with the music bed")

    @staticmethod
    def _publish(context: PipelineContext, target: Path) -> None:
        master = target.parent / "master.wav"
        if target != master:
            shutil.copy2(target, master)
        context.artifacts["audio_mix"] = str(target)
        context.artifacts["audio_master"] = str(target)
        context.metadata["audio_mix"] = {"path": str(target), "master": str(master)}

    def cache_outputs(self, context: PipelineContext) -> tuple[Path, ...]:
        path = context.artifacts.get("audio_mix")
        return (Path(path),) if path else ()
